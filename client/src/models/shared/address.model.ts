/**
 * Модель адреса (AddressModel)
 *
 * Представляет один физический адрес, связанный с пользователем или приёмом.
 * Используется как часть клиента (ClientModel), а также при записи на приём.
 *
 * Поля:
 * - id: уникальный идентификатор адреса (используется для редактирования, выбора и удаления)
 * - city: город (обязательное поле)
 * - street: улица (обязательное поле)
 * - building: номер дома (необязательное поле)
 * - apartment: номер квартиры или офиса (необязательное поле)
 * - additionalInfo: дополнительная информация (подъезд, код домофона и т.д.)
 * - isPrimary: является ли адрес основным для пользователя (опционально)
 */
export interface AddressModel {
	id: string;
	city: string;
	street: string;
	building: string;
	apartment?: string;
	additionalInfo?: string;
	isPrimary?: boolean;
}